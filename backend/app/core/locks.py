"""자문 잠금 키 — **한 곳에 모은다.**

PostgreSQL 의 자문 잠금은 숫자 하나가 전부다. 이름이 없으므로 두 자리에서
우연히 같은 수를 고르면 서로를 기다리게 되고, **그 사실을 아무도 모른다** —
로그에는 그냥 느려진 것으로 보인다. 키는 데이터가 아니라 약속이라 흩어지면
갈린다.
"""

# 표를 세우는 구간. 컨테이너 둘이 동시에 뜨면 같은 DDL 을 나란히 돌린다.
MIGRATION = 8_150_000

# 기준정보를 심는 구간.
SEED = 8_150_001

# **로트 번호를 짓는 구간.** 앞의 둘과 다르게 **두 번째 키를 함께 쓴다** —
# `pg_advisory_xact_lock(LOT_NUMBER, item_id)` 로 걸어 품목마다 따로 줄을 세운다.
# 품목이 다르면 서로 기다릴 이유가 없고, 같은 품목이면 그날의 마지막 번호를 둘이
# 동시에 읽어 **같은 번호를 짓는다.**
#
# 유일키가 그 사고를 막아 주기는 한다. 다만 막는 방식이 「둘째 요청이 터진다」라
# 검사원 쪽에서는 이유 없는 실패로 보인다 — 잠금은 그것을 **기다림**으로 바꾼다.
#
# **그 바꿈에는 전제가 있다.** 무엇이고 왜 코드에 박았는지는 `app/db/base.py` 의
# `create_db_engine` 이 적는다 — 여기 한 번 더 적으면 두 벌이 되고, 두 벌은 갈린다.
LOT_NUMBER = 8_150_002
